/**
 * Anime downloads end to end (Phase 6 Stage 5) through the queue and the real downloader, from a loopback host that
 * checks the video's headers on every request (a value with quotes, a comma and a semicolon, as KickAssAnime's
 * `sec-ch-ua`):
 * - a direct file streamed by the backend, with its subtitle and its external audio track (as KickAssAnime sends its
 *   audio apart; the live check found it) saved beside it; resumed with a `Range` request from what
 *   was staged; played by mpv (a fake) from the file, deleted;
 * - an HLS episode (generated by ffmpeg, its segments named `.jpg` as anime sites disguise them) through ffmpeg, its
 *   audio-only HLS track too; with
 *   ffmpeg made to fail, through yt-dlp; with both failing, FAILED with both reasons;
 * - the automatic downloads of new episodes after a library check (the setting and the category rule).
 *
 * The HLS cases need ffmpeg (and yt-dlp) where [DownloadTools] finds them, and are skipped without.
 */
class AnimeDownloadApiTest : AnimeApiTest() {
    private val host: HttpServer = HttpServer.create(InetSocketAddress("127.0.0.1", 0), 0)
    private val base get() = "http://127.0.0.1:${host.address.port}"

    private data class Seen(
        val path: String,
        val headers: Headers,
    )

    private val seen: MutableList<Seen> = Collections.synchronizedList(mutableListOf())

    /** The file: an MP4 signature, then bytes that tell their place. */
    private val file: ByteArray =
        ByteArray(300_000) { i -> (i * 31 % 251).toByte() }.also { b ->
            "\u0000\u0000\u0000 ftypisom".toByteArray(Charsets.ISO_8859_1).copyInto(b)
        }

    private val subtitle = "WEBVTT\n\n00:00.000 --> 00:01.000\nHello\n".toByteArray()

    /** An external audio track (an M4A signature), as KickAssAnime sends its audio apart from the video. */
    private val audio: ByteArray =
        ByteArray(20_000) { i -> (i * 7 % 253).toByte() }.also { b ->
            "\u0000\u0000\u0000\u0018ftypM4A ".toByteArray(Charsets.ISO_8859_1).copyInto(b)
        }

    private lateinit var hlsDir: File
    private var ffmpeg: File? = null
    private var ytDlp: File? = null

    private val sec = "\"Chromium\";v=\"130\", \"Not?A_Brand\";v=\"99\""

    private inner class DownloadSource : AnimeHttpSource() {
        override val name = "Download host"
        override val lang = "en"
        override val baseUrl get() = base
        override val supportsLatest = false

        @Volatile
        var path = "/file.mp4"

        @Volatile
        var audioPath = "/audio/ja.m4a"

        override suspend fun getHosterList(episode: SEpisode): List<Hoster> = listOf(Hoster(hosterUrl = "$base/h", hosterName = "Main"))

        override suspend fun getVideoList(hoster: Hoster): List<Video> =
            listOf(
                Video(
                    videoUrl = "$base$path",
                    videoTitle = "Main 720p",
                    resolution = 720,
                    headers = headersOf("Referer", "$base/", "sec-ch-ua", sec, "User-Agent", "Madoyomi test agent/1.0"),
                    subtitleTracks = listOf(Track("$base/subs/en.vtt", "English")),
                    audioTracks = listOf(Track("$base$audioPath", "Japanese")),
                ),
            )
    }

    @BeforeAll
    fun startHost() {
        host.createContext("/") { exchange ->
            exchange.use {
                val path = it.requestURI.path
                seen += Seen(path, Headers(it.requestHeaders))
                val ok = it.requestHeaders.getFirst("sec-ch-ua") == sec && it.requestHeaders.getFirst("Referer") == "$base/"
                when {
                    !ok -> {
                        it.sendResponseHeaders(403, -1)
                    }

                    path == "/file.mp4" -> {
                        val from =
                            it.requestHeaders
                                .getFirst("Range")
                                ?.removePrefix("bytes=")
                                ?.substringBefore('-')
                                ?.toInt() ?: 0
                        it.responseHeaders.add("Content-Type", "video/mp4")
                        if (from > 0) {
                            it.responseHeaders.add("Content-Range", "bytes $from-${file.size - 1}/${file.size}")
                            it.sendResponseHeaders(206, (file.size - from).toLong())
                        } else {
                            it.sendResponseHeaders(200, file.size.toLong())
                        }
                        it.responseBody.write(file, from, file.size - from)
                    }

                    path == "/audio/ja.m4a" -> {
                        it.responseHeaders.add("Content-Type", "audio/mp4")
                        it.sendResponseHeaders(200, audio.size.toLong())
                        it.responseBody.write(audio)
                    }

                    path == "/subs/en.vtt" -> {
                        it.responseHeaders.add("Content-Type", "text/vtt")
                        it.sendResponseHeaders(200, subtitle.size.toLong())
                        it.responseBody.write(subtitle)
                    }

                    path.startsWith("/hls/") && File(hlsDir, path.removePrefix("/hls/")).isFile -> {
                        val bytes = File(hlsDir, path.removePrefix("/hls/")).readBytes()
                        it.responseHeaders.add(
                            "Content-Type",
                            if (path.endsWith(".m3u8")) "application/vnd.apple.mpegurl" else "image/jpeg",
                        )
                        it.sendResponseHeaders(200, bytes.size.toLong())
                        it.responseBody.write(bytes)
                    }

                    else -> {
                        it.sendResponseHeaders(404, -1)
                    }
                }
            }
        }
        host.start()

        ffmpeg = runCatching { DownloadTools.find(DownloadTools.Tool.FFMPEG, override = null).file }.getOrNull()
        ytDlp = runCatching { DownloadTools.find(DownloadTools.Tool.YT_DLP, override = null).file }.getOrNull()
        hlsDir = Files.createTempDirectory("madoyomi-hls").toFile()
        ffmpeg?.let { exe ->
            // 4 s of test picture and tone in 1 s TS segments, named .jpg as some anime sites do
            val process =
                ProcessBuilder(
                    ProcessArgs.forPlatform(
                        listOf(
                            exe.path,
                            "-hide_banner",
                            "-loglevel",
                            "error",
                            "-y",
                            "-f",
                            "lavfi",
                            "-i",
                            "testsrc=duration=4:size=160x120:rate=10",
                            "-f",
                            "lavfi",
                            "-i",
                            "sine=frequency=440:duration=4",
                            "-c:v",
                            "mpeg2video",
                            "-c:a",
                            "mp2",
                            "-f",
                            "hls",
                            "-hls_time",
                            "1",
                            "-hls_list_size",
                            "0",
                            "-hls_segment_filename",
                            File(hlsDir, "seg%03d.jpg").path,
                            File(hlsDir, "index.m3u8").path,
                        ),
                    ),
                ).redirectErrorStream(true).start()
            process.inputStream.readBytes()
            check(process.waitFor(60, TimeUnit.SECONDS) && process.exitValue() == 0) { "ffmpeg could not make the test stream" }
            // and an audio-only stream, as a source's separate audio track
            val audioOnly =
                ProcessBuilder(
                    ProcessArgs.forPlatform(
                        listOf(
                            exe.path,
                            "-hide_banner",
                            "-loglevel",
                            "error",
                            "-y",
                            "-f",
                            "lavfi",
                            "-i",
                            "sine=frequency=220:duration=4",
                            "-c:a",
                            "mp2",
                            "-f",
                            "hls",
                            "-hls_time",
                            "1",
                            "-hls_list_size",
                            "0",
                            "-hls_segment_filename",
                            File(hlsDir, "aseg%03d.jpg").path,
                            File(hlsDir, "audio.m3u8").path,
                        ),
                    ),
                ).redirectErrorStream(true).start()
            audioOnly.inputStream.readBytes()
            check(audioOnly.waitFor(60, TimeUnit.SECONDS) && audioOnly.exitValue() == 0) { "ffmpeg could not make the audio stream" }
        }
    }

    @AfterAll
    fun stopHost() {
        host.stop(0)
        hlsDir.deleteRecursively()
    }

    private lateinit var root: File
    private lateinit var staging: File
    private lateinit var source: DownloadSource
    private val javaExe =
        ProcessHandle
            .current()
            .info()
            .command()
            .get()

    @BeforeEach
    fun fresh() {
        runBlocking { DownloadQueue.stop() }
        root = Files.createTempDirectory("madoyomi-downloads").toFile()
        staging = File(root, ".partial/anime")
        AnimeDownloads.downloadsRootOverride = root
        AnimeEpisodeDownloader.stagingRootOverride = staging
        AnimeEpisodeDownloader.progressIntervalMs = 0
        DownloadSettingsStore.fileOverride = Files.createTempFile("downloads", ".json").toFile().also { it.delete() }
        DownloadSettingsStore.reload()
        DownloadQueue.staggerMs = 0
        DownloadQueue.retryDelaysMs = listOf(10, 10)
        DownloadQueue.downloaders[ExtensionKind.ANIME] = AnimeEpisodeDownloader
        seen.clear()
        source = DownloadSource()
        register(source)
    }

    @AfterEach
    fun drop() {
        runBlocking { DownloadQueue.stop() }
        PlaybackSessions.stop()
        root.deleteRecursively()
        AnimeDownloads.downloadsRootOverride = null
        AnimeEpisodeDownloader.stagingRootOverride = null
        AnimeEpisodeDownloader.progressIntervalMs = 500
        DownloadSettingsStore.fileOverride?.delete()
        DownloadSettingsStore.fileOverride = null
        DownloadSettingsStore.reload()
        DownloadQueue.staggerMs = 1_000
        DownloadQueue.retryDelaysMs = listOf(5_000, 30_000)
        DownloadQueue.maxTries = 3
        DownloadQueue.downloaders[ExtensionKind.ANIME] = AnimeEpisodeDownloader
    }

    private fun episode(
        title: String = "Oshi no Ko",
        order: Int = 1,
    ): Pair<Int, Int> {
        val animeId = animeRow(source.id, "/$title", title = title, initialized = true)
        return animeId to episodeRow(animeId, "/$title/$order", order)
    }

    private fun download(vararg episodeIds: Int): Any? {
        val queued =
            graphql("mutation { enqueueDownloads(input: {kind: ANIME, itemIds: ${episodeIds.toList()}}) { queued } }")
                .assertNoErrors()
                .dataPath("enqueueDownloads", "queued")
        DownloadQueue.start()
        runBlocking { DownloadQueue.awaitIdle(120_000) }
        return queued
    }

    private fun completed(): List<Map<*, *>> =
        graphql("{ completedDownloads(kind: ANIME) { items { itemId state progressUnit progressDone progressTotal bytes totalBytes } } }")
            .assertNoErrors()
            .dataPath("completedDownloads", "items")
            .asList
            .map { it as Map<*, *> }

    private fun failed(): List<Map<*, *>> =
        graphql("{ downloadQueue { items { itemId state error } } }")
            .assertNoErrors()
            .dataPath("downloadQueue", "items")
            .asList
            .map { it as Map<*, *> }

    private fun requestsOf(prefix: String) = synchronized(seen) { seen.filter { it.path.startsWith(prefix) } }

    @Test
    fun `a direct file is streamed with the video's headers, its subtitle saved beside it, and the episode marked downloaded`() {
        val (animeId, episodeId) = episode()
        assertEquals(1, download(episodeId))

        val local = assertNotNull(AnimeDownloads.local(episodeId))
        assertEquals(EpisodeDownloadMethod.DIRECT, local.method)
        assertEquals(File(root, "anime/Download host (EN)/Oshi no Ko/Episode 1.mp4").canonicalFile, local.file.canonicalFile)
        assertContentEquals(file, local.file.readBytes())
        val (audioFile, audioLang) = local.audio.single()
        assertEquals("Episode 1.Japanese.audio.m4a", audioFile.name, "the external audio track beside it")
        assertEquals("Japanese", audioLang)
        assertContentEquals(audio, audioFile.readBytes())
        val (sub, lang) = local.subtitles.single()
        assertEquals("Episode 1.English.vtt", sub.name)
        assertEquals(local.file.parentFile.canonicalFile, sub.parentFile.canonicalFile)
        assertEquals("English", lang)
        assertContentEquals(subtitle, sub.readBytes())
        assertFalse(File(staging, episodeId.toString()).exists(), "the staging folder is gone")

        val fileRequest = requestsOf("/file.mp4").single()
        assertEquals("Madoyomi test agent/1.0", fileRequest.headers.getFirst("User-Agent"))
        assertEquals(sec, requestsOf("/subs/").single().headers.getFirst("sec-ch-ua"), "the subtitle with the headers too")

        val done = completed().single()
        assertEquals(episodeId, done["itemId"])
        assertEquals("BYTES", done["progressUnit"])
        assertEquals(1000, done["progressDone"])
        assertEquals((file.size + subtitle.size + audio.size).toString(), done["bytes"])
        assertEquals(file.size.toString(), done["totalBytes"])

        val data =
            graphql("{ anime(id: $animeId) { downloadCount episodes { nodes { id downloaded } } } }").assertNoErrors().dataPath("anime")
                as Map<*, *>
        assertEquals(1, data["downloadCount"])
        assertEquals(true, (data.path("episodes", "nodes").asList.single() as Map<*, *>)["downloaded"])
        assertEquals(0, download(episodeId), "a downloaded episode isn't queued again")
    }

    @Test
    fun `a direct file goes on from what was staged with a Range request`() {
        val (_, episodeId) = episode()
        val pick = runBlocking { AnimeEpisodeDownloader.pick(episodeId) }
        val dir = File(staging, episodeId.toString()).apply { mkdirs() }
        File(dir, "video.part").writeBytes(file.copyOfRange(0, 120_000))
        File(dir, "state.json").writeText(
            """{"hoster":"${pick.ref.hosterName}","title":"${pick.ref.videoTitle}","resolution":720,"ext":"mp4","totalBytes":${file.size}}""",
        )
        download(episodeId)

        assertEquals("bytes=120000-", requestsOf("/file.mp4").single().headers.getFirst("Range"))
        assertContentEquals(file, assertNotNull(AnimeDownloads.local(episodeId)).file.readBytes(), "the staged part and the rest")
    }

    @Test
    fun `a downloaded episode plays from its file in mpv, and deleting it removes the files and the mark`() {
        val (_, episodeId) = episode()
        download(episodeId)
        val local = assertNotNull(AnimeDownloads.local(episodeId))
        val java = javaExe
        val classes =
            File(
                FakeMpv::class.java.protectionDomain.codeSource.location
                    .toURI(),
            ).path
        val records = File(System.getProperty("java.io.tmpdir"), "madoyomi-fake-mpv")
        val defaultExecutable = PlaybackSessions.executable
        PlaybackSessions.executable = { listOf(java, "-cp", classes, "madoyomi.api.FakeMpv") }
        try {
            val session =
                graphql(
                    "mutation { playDownloadedEpisode(input: {episodeId: $episodeId, startSeconds: 42}) { session { id episodeId title } } }",
                ).assertNoErrors()
                    .dataPath("playDownloadedEpisode", "session") as Map<*, *>
            assertEquals(episodeId, session["episodeId"])
            assertEquals("Oshi no Ko - Episode 1", session["title"])
            val record = File(records, "madoyomi-mpv-${session["id"]}.txt")
            val deadline = System.currentTimeMillis() + 20_000
            while (!record.isFile) {
                check(System.currentTimeMillis() < deadline) { "the fake mpv recorded nothing" }
                Thread.sleep(50)
            }
            val text = record.readText().also { record.delete() }
            val args =
                text
                    .lineSequence()
                    .takeWhile { it != "INCLUDE" }
                    .filter {
                        it.startsWith(
                            "ARG ",
                        )
                    }.map { it.removePrefix("ARG ") }
                    .toList()
            assertEquals(local.file.absolutePath, args.last(), "the local file, not a URL")
            assertTrue("--start=42" in args)
            val include = text.substringAfter("INCLUDE\n")
            assertFalse("referrer" in include || "http-header-fields" in include, "no headers for a file: $include")
        } finally {
            PlaybackSessions.stop()
            PlaybackSessions.executable = defaultExecutable
        }
        assertTrue(seen.none { it.path.startsWith("/h") }, "nothing asked of the source to play it")

        val deleted =
            graphql("mutation { deleteDownloads(input: {kind: ANIME, itemIds: [$episodeId]}) { deleted } }")
                .assertNoErrors()
                .dataPath("deleteDownloads", "deleted")
        assertEquals(1, deleted)
        assertFalse(local.file.exists())
        assertFalse(
            local.subtitles
                .single()
                .first
                .exists(),
        )
        assertFalse(
            local.audio
                .single()
                .first
                .exists(),
        )
        assertNull(AnimeDownloads.local(episodeId))
        assertTrue(completed().isEmpty(), "off the completed list")
        assertEquals(
            "NOT_FOUND",
            graphql("mutation { playDownloadedEpisode(input: {episodeId: $episodeId}) { session { id } } }")
                .errors
                ?.single()
                ?.extensions
                ?.get("code"),
        )
    }

    @Test
    fun `an HLS episode goes through ffmpeg with the headers on every segment`() {
        assumeTrue(ffmpeg != null, "ffmpeg not found")
        source.path = "/hls/index.m3u8"
        source.audioPath = "/hls/audio.m3u8"
        val (_, episodeId) = episode()
        download(episodeId)

        val local = assertNotNull(AnimeDownloads.local(episodeId), "failed: ${failed()}")
        assertEquals(EpisodeDownloadMethod.FFMPEG, local.method)
        val (audioFile, _) = local.audio.single()
        assertEquals("Episode 1.Japanese.audio.mkv", audioFile.name, "the audio-only HLS track through ffmpeg too")
        assertTrue(audioFile.length() > 1000)
        val audioSegments = requestsOf("/hls/aseg")
        assertTrue(audioSegments.isNotEmpty() && audioSegments.all { it.headers.getFirst("sec-ch-ua") == sec })
        assertEquals("Episode 1.mkv", local.file.name)
        assertTrue(local.file.length() > 1000)
        assertEquals(1, local.subtitles.size, "the subtitle beside it")
        val segments = requestsOf("/hls/seg")
        assertTrue(segments.size >= 4, "every segment fetched: ${segments.map { it.path }}")
        segments.forEach {
            assertEquals(sec, it.headers.getFirst("sec-ch-ua"), "${it.path}: the header whole, quotes and all")
            assertEquals("Madoyomi test agent/1.0", it.headers.getFirst("User-Agent"))
        }
        val done = completed().single()
        assertEquals("SECONDS", done["progressUnit"])
        assertEquals(4, done["progressTotal"], "the duration ffmpeg reported")
    }

    @Test
    fun `when ffmpeg fails yt-dlp downloads the HLS episode, and when both fail the error names both`() {
        assumeTrue(ffmpeg != null && ytDlp != null, "ffmpeg or yt-dlp not found")
        source.path = "/hls/index.m3u8"
        // not ffmpeg: it exits with an error at once
        DownloadSettingsStore.update(DownloadSettings.Patch(ffmpegPath = javaExe))
        val (_, episodeId) = episode()
        download(episodeId)

        val local = assertNotNull(AnimeDownloads.local(episodeId), "failed: ${failed()}")
        assertEquals(EpisodeDownloadMethod.YT_DLP, local.method)
        assertTrue(local.file.length() > 1000)
        assertTrue(requestsOf("/hls/seg").all { it.headers.getFirst("sec-ch-ua") == sec })

        DownloadSettingsStore.update(DownloadSettings.Patch(ytDlpPath = javaExe))
        DownloadQueue.maxTries = 1
        val (_, second) = episode("Second", 1)
        download(second)
        val item = failed().single { it["itemId"] == second }
        assertEquals("FAILED", item["state"])
        val error = item["error"] as String
        assertTrue("ffmpeg failed" in error && "yt-dlp failed" in error, error)
    }

    @Test
    fun `new episodes are downloaded after a library check when the setting is on, by the category rule`() {
        val queued = Collections.synchronizedList(mutableListOf<Int>())
        DownloadQueue.downloaders[ExtensionKind.ANIME] =
            object : ItemDownloader {
                override suspend fun download(
                    item: DownloadItem,
                    progress: suspend (DownloadProgress) -> Unit,
                ): Long {
                    queued += item.itemId
                    return 1
                }
            }
        val (animeId, episodeId) = episode()
        val entry = LibraryUpdater.Entry(ExtensionKind.ANIME, animeId, "Oshi no Ko", source.id)

        AnimeDownloads.autoDownload(entry, listOf(episodeId))
        assertTrue(DownloadQueue.items(ExtensionKind.ANIME).isEmpty(), "off by default")

        DownloadSettingsStore.update(DownloadSettings.Patch(autoDownload = true))
        val excluded = AnimeCategories.create("Not these", includeInDownload = IncludeOrExclude.EXCLUDE)
        AnimeCategories.assign(listOf(animeId), add = listOf(excluded), remove = emptyList())
        AnimeDownloads.autoDownload(entry, listOf(episodeId))
        assertTrue(DownloadQueue.items(ExtensionKind.ANIME).isEmpty(), "a category with Downloads off")

        AnimeCategories.assign(listOf(animeId), add = emptyList(), remove = listOf(excluded))
        AnimeDownloads.autoDownload(entry, listOf(episodeId))
        assertEquals(listOf(episodeId), DownloadQueue.items(ExtensionKind.ANIME).map { it.itemId }, "Default, with no flag set")
        DownloadQueue.start()
        runBlocking { DownloadQueue.awaitIdle() }
        assertEquals(listOf(episodeId), queued.toList())
    }
